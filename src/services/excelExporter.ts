/**
 * Generates an Excel workbook for a single Slitter Plan matching GPAK/QR/PL/01
 */
export function exportSinglePlanToExcel(plan: SlitterPlan): Uint8Array {
  const wb = XLSX.utils.book_new();
  const ws = createPlanWorksheet(plan);
  XLSX.utils.book_append_sheet(wb, ws, plan.plan_number.slice(0, 31));
  return XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
}

/**
 * Generates a complete Multi-Plan Planning Run Excel Workbook
 * Contains Summary Sheet + Individual Plan Sheets + Remaining Demand Sheet
 */
/**
 * Download All: one workbook, each plan on its own sheet (Plan1, Plan2, …).
 * Same as exportCompleteRunToExcel — kept as explicit alias for UI.
 */
export function exportAllPlansToExcel(
  run: PlanningRun,
  plans: SlitterPlan[],
  remainingOrders: VA05Order[] = []
): Uint8Array {
  return exportCompleteRunToExcel(run, plans, remainingOrders);
}

export function exportCompleteRunToExcel(
  run: PlanningRun,
  plans: SlitterPlan[],
  remainingOrders: VA05Order[]
): Uint8Array {
  const wb = XLSX.utils.book_new();

  // 1. Run Summary Sheet
  const summaryData = [
    ['PRIMARY SLITTER PLANNING RUN SUMMARY'],
    ['Run Number:', run.run_number, 'Film Grade:', run.film],
    ['Target Quantity (kg):', run.target_quantity_kg, 'Planned Quantity (kg):', run.planned_quantity_kg],
    ['Target Range (±5%):', run.target_min_kg ? `${run.target_min_kg} - ${run.target_max_kg} kg` : 'N/A', 'Target Deviation:', `${run.target_deviation_percent !== undefined ? run.target_deviation_percent : 0}%`],
    ['Remaining Quantity (kg):', run.remaining_quantity_kg, 'Plans Generated:', plans.length],
    ['Orders Completely Closed:', run.orders_closed_count, 'Orders Partially Fulfilled:', run.orders_partial_count],
    ['Trim Mode:', run.trim_rule_mode || 'NORMAL', 'Trim Limits:', `${run.min_trim_mm_used || 150} - ${run.max_trim_mm_used || 280} mm`],
    ['Status:', run.status, 'Generated By:', run.created_by],
    ['Created At:', run.created_at, 'Stop Reason:', run.stop_reason || 'N/A'],
    [],
    ['PLAN SUMMARY TABLE'],
    ['Plan No.', 'Film', 'UPS', 'Deckle (mm)', 'Slit Width (mm)', 'Trim (mm)', 'Length (m)', 'Reps', 'MR Length (m)', 'Planned Qty (kg)', 'Status'],
  ];

  plans.forEach(p => {
    summaryData.push([
      p.plan_number,
      p.film,
      p.ups,
      p.deckle_mm,
      p.total_slit_width_mm,
      p.trim_mm,
      p.length_m,
      p.repetitions,
      p.planned_mr_length_m,
      p.planned_quantity_kg,
      p.status,
    ]);
  });

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryData);
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Summary');

  // 2. Individual Plan Sheets — exact factory sample format (Plan1, Plan2, …)
  plans.forEach((plan, idx) => {
    const wsPlan = createPlanWorksheet(plan);
    XLSX.utils.book_append_sheet(wb, wsPlan, sheetNameForPlan(idx, plan.plan_number));
  });

  // 3. Remaining Orders Sheet
  const remainingData: any[][] = [
    ['REMAINING DEMAND BACKLOG AFTER PLANNING RUN'],
    ['Film:', run.film, 'Run ID:', run.run_number],
    [],
    ['SO#', 'Item#', 'Customer', 'Width (mm)', 'Length (m)', 'Core', 'TS', 'Original Qty (kg)', 'Produced (kg)', 'Remaining Qty (kg)', 'Status', 'Delivery Date'],
  ];

  remainingOrders.forEach(o => {
    remainingData.push([
      o.sales_order,
      o.item_number,
      o.customer,
      o.width_mm,
      o.length_m,
      o.core,
      o.treatment_side,
      o.balance_qty,
      o.produced_qty,
      o.remaining_qty,
      o.status,
      o.delivery_date || '',
    ]);
  });

  const wsRemaining = XLSX.utils.aoa_to_sheet(remainingData);
  XLSX.utils.book_append_sheet(wb, wsRemaining, 'Remaining Demand');

  return XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
}

