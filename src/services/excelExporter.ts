export function formatNumberRangeList(nums: number[]): string {
  if (!nums || nums.length === 0) return '';
  const sorted = Array.from(new Set(nums.filter(n => typeof n === 'number' && !isNaN(n)))).sort((a, b) => a - b);
  if (sorted.length === 0) return '';
  if (sorted.length === 1) return `${sorted[0]}`;

  const ranges: string[] = [];
  let start = sorted[0];
  let end = sorted[0];

  for (let i = 1; i < sorted.length; i++) {
    if (sorted[i] === end + 1) {
      end = sorted[i];
    } else {
      ranges.push(start === end ? `${start}` : `${start}–${end}`);
      start = sorted[i];
      end = sorted[i];
    }
  }
  ranges.push(start === end ? `${start}` : `${start}–${end}`);
  return ranges.join(', ');
}

/**
 * Consolidates plan items sharing the same Sales Order, Item Number, Customer, Size, Core, Treatment & Length.
 * Combines individual UPS cuts into a single unified execution row with total UPS count, total deckle, and total weight.
 */
export function consolidatePlanItems(items: PlanItem[] = []): ConsolidatedPlanItemRow[] {
  if (!items || items.length === 0) return [];

  const map = new Map<string, PlanItem[]>();

  items.forEach(item => {
    // FUTURE SHIFT only when engine marked a true size-change replacement.
    // start_pack > 1 alone (same size, different customer/SO/item) is NOT future shift.
    const isFuture = !!item.is_future_replacement;
    const soClean = (item.sales_order || '').trim();
    const itemNumClean = `${item.item_number || ''}`.trim();
    const custClean = (item.customer || '').trim();
    const w = Number(item.width_mm || 0);
    const l = Number(item.length_m || 0);
    const c = `${item.core || ''}`.trim();
    const ts = (item.treatment_side || '').trim();

    const key = `${soClean}__${itemNumClean}__${custClean}__${w}__${l}__${c}__${ts}__${isFuture ? '1' : '0'}`;
    if (!map.has(key)) {
      map.set(key, []);
    }
    map.get(key)!.push(item);
  });

  const consolidated: ConsolidatedPlanItemRow[] = [];

  map.forEach((groupedItems, key) => {
    const first = groupedItems[0];
    const isFuture = !!first.is_future_replacement;

    // Total UPS sum: only active items count towards initial active UPS
    const totalUps = isFuture ? 0 : groupedItems.reduce((sum, it) => {
      const up = it.is_future_replacement ? 0 : (it.initial_ups !== undefined ? it.initial_ups : (it.ups || 1));
      return sum + up;
    }, 0);

    // Sum Total Weight
    const totalWeightKg = Number(groupedItems.reduce((sum, it) => sum + (it.total_weight_kg || 0), 0).toFixed(2));

    // Sum Reels
    const totalReels = groupedItems.reduce((sum, it) => sum + (it.reels || 0), 0);

    // Sum Weight per pack
    const totalWeightPerPack = Number(groupedItems.reduce((sum, it) => sum + (it.weight_per_pack_kg || 0), 0).toFixed(2));

    // Deckle (mm)
    const deckleMm = isFuture ? 0 : (first.width_mm * totalUps);

    // Collect all Positions and Arm numbers
    const allPositions: number[] = [];
    const allArms: number[] = [];

    groupedItems.forEach((it, idx) => {
      let foundPosInLabel = false;
      let foundArmInLabel = false;

      if (it.position_label) {
        const posMatch = it.position_label.match(/Pos\s*([0-9,\s–-]+)/i);
        const armMatch = it.position_label.match(/Arm\s*([0-9,\s–-]+)/i);

        if (posMatch) {
          foundPosInLabel = true;
          const matchedStr = posMatch[1];
          const chunks = matchedStr.split(/[,]/);
          chunks.forEach(ch => {
            const range = ch.trim().split(/[–-]/);
            if (range.length === 2) {
              const rStart = parseInt(range[0].trim(), 10);
              const rEnd = parseInt(range[1].trim(), 10);
              if (!isNaN(rStart) && !isNaN(rEnd)) {
                for (let n = rStart; n <= rEnd; n++) allPositions.push(n);
              }
            } else if (range.length === 1) {
              const single = parseInt(range[0].trim(), 10);
              if (!isNaN(single)) allPositions.push(single);
            }
          });
        }

        if (armMatch) {
          foundArmInLabel = true;
          const matchedStr = armMatch[1];
          const chunks = matchedStr.split(/[,]/);
          chunks.forEach(ch => {
            const range = ch.trim().split(/[–-]/);
            if (range.length === 2) {
              const rStart = parseInt(range[0].trim(), 10);
              const rEnd = parseInt(range[1].trim(), 10);
              if (!isNaN(rStart) && !isNaN(rEnd)) {
                for (let n = rStart; n <= rEnd; n++) allArms.push(n);
              }
            } else if (range.length === 1) {
              const single = parseInt(range[0].trim(), 10);
              if (!isNaN(single)) allArms.push(single);
            }
          });
        }
      }

      if (!foundPosInLabel) {
        if (it.positions && it.positions.length > 0) {
          it.positions.forEach(p => allPositions.push(p));
        } else if (it.position !== undefined) {
          allPositions.push(it.position);
        }
      }

      if (!foundArmInLabel && it.position !== undefined) {
        allArms.push(it.position);
      }
    });

    const posRangeStr = formatNumberRangeList(allPositions);
    const armRangeStr = formatNumberRangeList(allArms);

    let posLabel = first.position_label || `${first.position || 1}`;
    if (posRangeStr && armRangeStr && posRangeStr !== armRangeStr) {
      posLabel = `Pos ${posRangeStr} (Arms ${armRangeStr})`;
    } else if (posRangeStr) {
      posLabel = `Pos ${posRangeStr}`;
    } else if (armRangeStr) {
      posLabel = `Arm ${armRangeStr}`;
    }

    // Stations
    const countA = groupedItems.filter(it => (it.station || (it.position <= 8 ? 'SIDE_A' : 'SIDE_B')) === 'SIDE_A').length;
    const countB = groupedItems.filter(it => (it.station || (it.position <= 8 ? 'SIDE_A' : 'SIDE_B')) === 'SIDE_B').length;

    let station: 'SIDE_A' | 'SIDE_B' | 'MIXED' = 'SIDE_A';
    let stationLabel = 'SIDE A';

    if (countA > 0 && countB === 0) {
      station = 'SIDE_A';
      stationLabel = 'SIDE A';
    } else if (countB > 0 && countA === 0) {
      station = 'SIDE_B';
      stationLabel = 'SIDE B';
    } else if (countA > 0 && countB > 0) {
      station = 'MIXED';
      stationLabel = `A: ${countA} | B: ${countB}`;
    }

    consolidated.push({
      key,
      id: first.id,
      position_label: posLabel,
      station,
      station_label: stationLabel,
      sales_order: first.sales_order,
      item_number: first.item_number,
      customer: first.customer,
      film: first.film,
      length_m: first.length_m,
      core: first.core,
      treatment_side: first.treatment_side,
      width_mm: first.width_mm,
      total_weight_kg: totalWeightKg,
      size_mm: first.width_mm,
      ups: totalUps,
      deckle_mm: deckleMm,
      reels: totalReels,
      weight_per_pack_kg: totalWeightPerPack,
      is_closed: groupedItems.every(it => it.is_closed),
      is_future_replacement: isFuture,
      start_pack: first.start_pack,
      active_packs: first.active_packs,
      replacement_instruction: first.replacement_instruction || (isFuture && first.start_pack ? `Starts after Pack ${first.start_pack - 1}` : undefined),
      raw_items: groupedItems,
    });
  });

  // Order rows so each FUTURE SHIFT sits directly under the active size/position
  // it replaces (change-from size → change-to row immediately below).
  const getPositions = (row: ConsolidatedPlanItemRow): number[] => {
    const nums: number[] = [];
    for (const it of row.raw_items || []) {
      if (typeof it.position === 'number' && !isNaN(it.position)) nums.push(it.position);
      if (Array.isArray((it as any).positions)) {
        for (const p of (it as any).positions) {
          if (typeof p === 'number') nums.push(p);
        }
      }
    }
    const label = row.position_label || '';
    const matches = label.matchAll(/\d+/g);
    for (const m of matches) {
      const n = Number(m[0]);
      if (!isNaN(n) && n > 0 && n < 100) nums.push(n);
    }
    return Array.from(new Set(nums));
  };

  const actives = consolidated.filter(r => !r.is_future_replacement);
  const futures = consolidated.filter(r => !!r.is_future_replacement);

  actives.sort((a, b) => {
    const pa = getPositions(a);
    const pb = getPositions(b);
    const ma = pa.length ? Math.min(...pa) : 999;
    const mb = pb.length ? Math.min(...pb) : 999;
    if (ma !== mb) return ma - mb;
    return (b.width_mm || 0) - (a.width_mm || 0);
  });

  const ordered: ConsolidatedPlanItemRow[] = [];
  const usedFutureKeys = new Set<string>();

  for (const active of actives) {
    ordered.push(active);
    const activePos = new Set(getPositions(active));
    const activeW = Number(active.width_mm || 0);

    const related = futures
      .filter(f => {
        if (usedFutureKeys.has(f.key)) return false;
        const fPos = getPositions(f);
        // Same physical arm/position → this shift belongs under that active row
        if (fPos.some(p => activePos.has(p))) return true;
        // Instruction "CHANGE SIZE {activeW}MM → ..."
        const instr = `${f.replacement_instruction || ''} ${f.raw_items?.map(r => r.replacement_instruction || '').join(' ') || ''}`;
        if (activeW > 0 && new RegExp(`CHANGE SIZE\\s*${activeW}\\s*MM`, 'i').test(instr)) return true;
        // start_pack replacement on same SO chain under this width group
        return false;
      })
      .sort((a, b) => (a.start_pack || 0) - (b.start_pack || 0) || (a.width_mm || 0) - (b.width_mm || 0));

    for (const f of related) {
      ordered.push(f);
      usedFutureKeys.add(f.key);
    }
  }

  for (const f of futures) {
    if (!usedFutureKeys.has(f.key)) ordered.push(f);
  }

  return ordered.length > 0 ? ordered : consolidated;
}

